"""Noether-style loop invariant inference experiment.

Hypothesis under test (combo:noether-loop-invariants):
    Loop invariants are conserved quantities generated by symmetries of the
    loop's transition relation; inference becomes symmetry detection.

Pipeline per loop:
  1. SYMBOLIC REPRESENTATION
     The transition relation is a system of polynomial next-state maps
     x' = f(x) (one branch per conditional route), represented exactly over
     Fraction coefficients (loops.py).

  2. SYMMETRY DETECTION
     Search the family of homogeneous linear state transformations
     T: x_i |-> c * x_sigma(i)  (variable permutations composed with sign
     flips and small scalings c in {+-1, +-2, +-3, +-4, +-9}) for automorphisms
     of the transition relation, i.e. T o f = f o T on every branch (exact
     polynomial identity check).

  3. CANDIDATE GENERATION FROM SYMMETRIES
     (a) Finite symmetries: expand each detected T on the monomial basis of
         degree <= 2; extract eigenforms q with T(q) = lambda*q for rational
         lambda (exact rational nullspaces of M - lambda*I). Eigenforms are
         "symmetry-covariant quantities" -- the discrete-Noether analogue of
         currents.
     (b) Translation duality: if every branch is a pure translation
         (f(x) - x constant), then translation by its own displacement is a
         symmetry of the transition relation; its fixed linear forms
         (ell . Delta = 0, solved exactly) are candidate conserved quantities.

  4. INDUCTIVE VALIDATION
     A candidate q with k = q(init) is accepted iff, on every branch,
     q(f(x)) == q(x)   (conserved), or
     q(f(x)) == kappa*q(x) for a rational kappa and k == 0
                       (zero level set preserved by covariance),
     checked as exact polynomial identities, plus a numeric sanity pass over
     all states reachable from init.

  5. VERIFICATION-GRADE TEST
     The loop counts as HIT iff the validated candidate equations entail the
     annotated post-condition t == c, decided by bounded exact reduction:
     repeatedly solve validated equations that are linear in some variable
     and substitute into t until t collapses to a constant.

Metrics:
  extended coverage : hits / total using all symmetry-derived candidates
                      (finite + translation duality)
  strict coverage   : hits / total using only finite-automorphism eigenforms

Usage: python3 run.py [--markdown]
"""

import sys
from fractions import Fraction

from loops import (build_loops, padd, pneg, psub, pscale, pmul, peval,
                   degree, substitute, pident, pstr, lin)

# ---------------------------------------------------------------- helpers

def holds(op, val):
    return {"<": val < 0, "<=": val <= 0, ">": val > 0, ">=": val >= 0,
            "==": val == 0, "!=": val != 0}[op]


def simulate(lp, cap=600):
    """All states reachable from init while the guard holds (numeric)."""
    state = list(lp.init)
    states = [tuple(state)]
    for _ in range(cap):
        if not all(holds(op, peval(p, state)) for op, p in lp.guard):
            break
        for conds, upd in lp.branches:
            if conds is None or all(holds(op, peval(p, state))
                                    for op, p in conds):
                state = [int(peval(u, state))
                         for _, u in sorted(upd.items())]
                break
        states.append(tuple(state))
    return states


def nullspace(rows):
    """Nullspace basis (list of tuples) of a matrix given as rows over
    Fractions. rows may be empty -> no constraint -> None (caller decides)."""
    if not rows:
        return None
    m, n = len(rows), len(rows[0])
    a = [list(map(Fraction, r)) for r in rows]
    pivots = []
    r = 0
    for c in range(n):
        pr = next((i for i in range(r, m) if a[i][c] != 0), None)
        if pr is None:
            continue
        a[r], a[pr] = a[pr], a[r]
        pv = a[r][c]
        a[r] = [x / pv for x in a[r]]
        for i in range(m):
            if i != r and a[i][c] != 0:
                f = a[i][c]
                a[i] = [x - f * y for x, y in zip(a[i], a[r])]
        pivots.append(c)
        r += 1
        if r == m:
            break
    free = [c for c in range(n) if c not in pivots]
    basis = []
    for fc in free:
        v = [Fraction(0)] * n
        v[fc] = Fraction(1)
        for i, pc in enumerate(pivots):
            v[pc] = -a[i][fc]
        basis.append(tuple(v))
    return basis


def normalize_vec(v):
    nz = next((x for x in v if x != 0), None)
    if nz is None:
        return None
    w = tuple(x / nz for x in v)
    # sign-canonical: first nonzero positive
    if next(x for x in w if x != 0) < 0:
        w = tuple(-x for x in w)
    return w


# ------------------------------------------------------ step 2: detection

COEFS = [Fraction(1), Fraction(-1), Fraction(2), Fraction(-2),
         Fraction(3), Fraction(-3), Fraction(4), Fraction(-4),
         Fraction(9), Fraction(-9)]
COEFS_BIG_N = [Fraction(1), Fraction(-1), Fraction(2), Fraction(-2)]


def enumerate_transforms(n):
    """Yield (desc, image_map) for homogeneous linear candidate T:
    var i -> coefs[i] * var perm[i]."""
    from itertools import permutations, product as iproduct
    perms = list(permutations(range(n)))
    coefs = COEFS if n <= 2 else COEFS_BIG_N
    for perm in perms:
        for choice in iproduct(coefs, repeat=n):
            if perm == tuple(range(n)) and all(c == 1 for c in choice):
                continue
            image = {i: {tuple(1 if j == perm[i] else 0 for j in range(n)):
                         choice[i]}
                     for i in range(n)}
            desc = ("".join(
                f"{'+' if c > 0 else '-'}{'' if abs(c) == 1 else abs(c)}"
                f"x{i}->{perm[i]} "
                for i, c in enumerate(choice))).strip()
            yield desc, image


def commutes(lp, image):
    """T o f == f o T on every branch, as exact poly identities."""
    for _, upd in lp.branches:
        # T applied to the map f: substitute image into each update
        lhs = {v: substitute(u, image) for v, u in upd.items()}
        # f applied to T: express T(var) after stepping: substitute updates
        rhs = {v: substitute(image[v], upd) for v in range(lp.n)}
        for v in range(lp.n):
            if not pident(lhs[v], rhs[v]):
                return False
    return True


def detect_symmetries(lp):
    syms = []
    for desc, image in enumerate_transforms(lp.n):
        if commutes(lp, image):
            syms.append((desc, image))
    return syms


# --------------------------------------------- step 3a: finite-sym eigs

LAMBDAS = ([Fraction(s * d) for s in (1, -1) for d in
            (1, 2, 3, 4, 6, 8, 9, 12, 16, 27, 81)] +
           [Fraction(s, d) for s in (1, -1) for d in
            (2, 3, 4, 6, 8, 9, 16, 27, 81)] +
           [Fraction(2, 3), Fraction(3, 2), Fraction(4, 3),
            Fraction(3, 4)])


def monomial_basis(n, maxdeg=2):
    from itertools import product as iproduct
    basis = [m for m in iproduct(range(maxdeg + 1), repeat=n)
             if sum(m) <= maxdeg]
    return sorted(basis, key=lambda m: (sum(m), m))


def eigen_candidates(lp, image, maxdeg=2):
    """Eigenforms q (deg <= maxdeg) of one transformation T."""
    basis = monomial_basis(lp.n, maxdeg)
    index = {m: i for i, m in enumerate(basis)}
    dim = len(basis)

    def T_monomial(m):
        coef = Fraction(1)
        exp = [0] * lp.n
        for i, e in enumerate(m):
            if e:
                img = image[i]
                (me,), (mc,) = list(img.keys()), list(img.values())
                coef *= mc ** e
                for j in range(lp.n):
                    exp[j] += me[j] * e
        return coef, tuple(exp)

    # matrix of T on the coefficient space
    cols = []
    for m in basis:
        col = [Fraction(0)] * dim
        coef, tm = T_monomial(m)
        col[index[tm]] += coef
        cols.append(col)
    rowsM = [[cols[j][i] for j in range(dim)] for i in range(dim)]

    out = []
    for lam in LAMBDAS:
        rows = [[rowsM[i][j] - (lam if i == j else 0) for j in range(dim)]
                for i in range(dim)]
        ns = nullspace(rows)
        if not ns:
            continue
        for vec in ns:
            nv = normalize_vec(vec)
            if nv is None:
                continue
            poly = {}
            for m, c in zip(basis, nv):
                if c != 0:
                    poly[m] = c
            out.append((lam, poly))
    return out


# ------------------------------------------ step 3b: translation duality

def translation_candidates(lp):
    """If every branch is a pure translation, the displacement(s) define a
    translation symmetry; fixed linear forms ell (ell.Delta_b = 0 for every
    branch b) are candidate conserved quantities."""
    deltas = []
    for _, upd in lp.branches:
        d = []
        for v in range(lp.n):
            diff = padd(upd[v], pneg(lin(lp.n, {v: 1})))
            if any(sum(m) >= 1 for m in diff):
                return []          # not a pure translation on this branch
            d.append(sum(c for m, c in diff.items()
                         if all(e == 0 for e in m)))
        deltas.append(d)
    ns = nullspace(deltas)         # rows: ell . Delta_b = 0
    out = []
    for vec in ns or []:
        poly = lin(lp.n, {i: int(c) if c == int(c) else c
                          for i, c in enumerate(vec) if c != 0})
        out.append(poly)
    return out


# ------------------------------------------------ step 4: validation

def infer_kappa(g, q, lp):
    """Guess rational kappa with g == kappa*q; verify exactly."""
    pts = []
    import random
    rng = random.Random(20260821)
    for _ in range(8):
        pt = [rng.randint(-20, 20) for _ in range(lp.n)]
        qv = peval(q, pt)
        if qv != 0:
            kappa = peval(g, pt) / qv
            return kappa if pident(g, pscale(q, kappa)) else None
    return None


def validate_candidate(lp, q, reached):
    """Return claim dict if q is an inductive assertion, else None."""
    k = peval(q, lp.init)
    covariant = False
    for bi, (_, upd) in enumerate(lp.branches):
        g = substitute(q, upd)
        if pident(g, q):
            continue
        kappa = infer_kappa(g, q, lp)
        if kappa is not None and k == 0:
            covariant = True
            continue
        return None
    # numeric sanity over reachable states
    for st in reached:
        if peval(q, st) != k:
            return None
    kind = ("conserved" if not covariant else "covariant-zero")
    return {"poly": q, "const": k, "kind": kind}


# --------------------------------------- step 5: verification-grade test

def linear_in_var(q, v, lp_n):
    """If q is affine-linear in variable v, return (coeff, rest_poly).
    rest_poly keeps full-length monomials with the v-component zeroed,
    i.e. q == coeff * x_v + rest."""
    coeff = Fraction(0)
    rest = {}
    for mm, c in q.items():
        m = mm + (0,) * max(0, lp_n - len(mm))
        if m[v] > 1:
            return None
        if m[v] == 1:
            if any(e > 0 for i, e in enumerate(m) if i != v):
                return None          # x_v * (something) : not affine in x_v
            coeff += c
        else:
            rest[m] = rest.get(m, Fraction(0)) + c
    rest = {m: c for m, c in rest.items() if c != 0}
    if coeff == 0:
        return None
    return coeff, rest


def entails(candidates, target, target_const, lp, passes=6):
    """Bounded exact reduction: solve candidate eqs linear-in-a-var and
    substitute into target; success iff target becomes the constant."""
    if target is None:
        return False, "no polynomial target"
    t = dict(target)
    for _ in range(passes):
        changed = False
        for cand in candidates:
            q, k = cand["poly"], cand["const"]
            for v in range(lp.n):
                sol = linear_in_var(q, v, lp.n)
                if sol is None:
                    continue
                coeff, rest = sol
                # v = (k - rest)/coeff
                vpoly = pscale(padd({(): Fraction(k)}, pneg(rest)),
                               Fraction(1) / coeff)
                sub = {i: lin(lp.n, {i: 1}) for i in range(lp.n)}
                sub[v] = vpoly
                t2 = substitute(t, sub)
                if not pident(t2, t):
                    t = t2
                    changed = True
                    break
        if not changed:
            break
    if degree(t) == 0:
        val = t.get((), Fraction(0))
        return val == target_const, f"{pstr(t, lp.vars)} (reduced)"
    return False, f"residual {pstr(t, lp.vars)}"


# ------------------------------------------------------------ driver

def run_loop(lp, verbose=True):
    reached = simulate(lp)
    syms = detect_symmetries(lp)

    # candidates from finite symmetries
    finite = []
    seen = set()
    for desc, image in syms:
        eigs = eigen_candidates(lp, image)
        forms = []
        for lam, poly in eigs:
            forms.append((lam, poly))
        # combine eigenforms sharing the same lambda: sums and differences
        by_lam = {}
        for lam, poly in forms:
            by_lam.setdefault(lam, []).append(poly)
        combined = list(forms)
        for lam, polys in by_lam.items():
            for i in range(len(polys)):
                for j in range(i + 1, len(polys)):
                    combined.append((lam, padd(polys[i], polys[j])))
                    combined.append((lam, psub(polys[i], polys[j])))
        for lam, poly in combined:
            if not poly:
                continue
            key = normalize_vec(tuple(poly.get(m, Fraction(0))
                                      for m in monomial_basis(lp.n)))
            if key is None or key in seen:
                continue
            seen.add(key)
            finite.append((desc, lam, poly))

    trans = translation_candidates(lp)

    def dedup(polys):
        out, seenn = [], set()
        for p in polys:
            key = normalize_vec(tuple(p.get(m, Fraction(0))
                                      for m in monomial_basis(lp.n)))
            if key is None or key in seenn:
                continue
            seenn.add(key)
            out.append(p)
        return out

    results = {"finite": [], "translation": []}
    for tag, pool in (("finite", [p for _, _, p in finite]),
                      ("translation", trans)):
        for q in dedup(pool):
            claim = validate_candidate(lp, q, reached)
            if claim:
                results[tag].append(claim)

    # verification-grade test, strict then extended
    ok_strict, why_s = entails(results["finite"], lp.target,
                               lp.target_const, lp)
    ok_ext, why_e = entails(results["finite"] + results["translation"],
                            lp.target, lp.target_const, lp)

    if verbose:
        print(f"=== {lp.name}: {lp.desc}")
        print(f"    guard: {lp.guard_str}; vars={lp.vars}; init={lp.init}")
        print(f"    known invariant(s): {'; '.join(lp.invariant_strs)}")
        print(f"    detected transition automorphisms: "
              f"{len(syms)}" + (f" e.g. {syms[0][0]}" if syms else ""))
        print(f"    finite-sym eigenform candidates kept: "
              f"{len(results['finite'])}")
        for c in results["finite"][:6]:
            print(f"      [{c['kind']}] {pstr(c['poly'], lp.vars)} "
                  f"== {c['const']}")
        print(f"    translation-duality candidates kept: "
              f"{len(results['translation'])}")
        for c in results["translation"][:6]:
            print(f"      [{c['kind']}] {pstr(c['poly'], lp.vars)} "
                  f"== {c['const']}")
        print(f"    target: {pstr(lp.target, lp.vars) if lp.target is not None else lp.invariant_strs[0]}"
              f" == {lp.target_const}")
        print(f"    strict hit: {ok_strict} ({why_s})")
        print(f"    extended hit: {ok_ext} ({why_e})")
        print()

    return {"loop": lp, "n_syms": len(syms), "results": results,
            "hit_strict": ok_strict, "hit_ext": ok_ext,
            "why_strict": why_s, "why_ext": why_e,
            "n_reached": len(reached)}


def main():
    markdown = "--markdown" in sys.argv
    loops = build_loops()
    rows = [run_loop(lp) for lp in loops]

    total = len(rows)
    ext_hits = sum(r["hit_ext"] for r in rows)
    strict_hits = sum(r["hit_strict"] for r in rows)
    misses = [r for r in rows if not r["hit_ext"]]

    print("=" * 72)
    print(f"loops: {total}")
    print(f"extended coverage (finite + translation duality): "
          f"{ext_hits}/{total} = {100 * ext_hits / total:.1f}%")
    print(f"strict coverage (finite automorphisms only):       "
          f"{strict_hits}/{total} = {100 * strict_hits / total:.1f}%")
    print(f"threshold: 20%  ->  extended "
          f"{'PASS' if ext_hits / total >= 0.2 else 'FAIL'}; strict "
          f"{'PASS' if strict_hits / total >= 0.2 else 'FAIL'}")
    print("misses:", ", ".join(r["loop"].name for r in misses))

    if markdown:
        print("\n| loop | #automorphisms | candidates kept (finite/trans)"
              "| strict | extended | note |")
        print("|---|---|---|---|---|---|")
        for r in rows:
            lp = r["loop"]
            note = lp.notes or ""
            print(f"| {lp.name} | {r['n_syms']} "
                  f"| {len(r['results']['finite'])}/"
                  f"{len(r['results']['translation'])} "
                  f"| {'HIT' if r['hit_strict'] else 'miss'} "
                  f"| {'HIT' if r['hit_ext'] else 'MISS'} | {note} |")


if __name__ == "__main__":
    main()
